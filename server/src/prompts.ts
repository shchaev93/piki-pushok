const FOOD_NAMES: Record<string, string> = { seeds: 'семечки', apple: 'яблоко', carrot: 'морковка', cheese: 'сыр', bread: 'хлебушек' };
const DISH_NAMES: Record<string, string> = { pie: 'пирог', sandwich: 'бутерброд', salad: 'салат', soup: 'суп-сюрприз' };

function pantryText(basket: Record<string, number> | undefined): string {
  const parts = Object.entries(basket ?? {})
    .filter(([id, n]) => FOOD_NAMES[id] && n > 0)
    .map(([id, n]) => `${FOOD_NAMES[id]} ${n}`);
  return parts.length ? parts.join(', ') : 'пусто';
}

function dishesText(dishes: string[] | undefined): string {
  const count = new Map<string, number>();
  for (const d of dishes ?? []) if (DISH_NAMES[d]) count.set(DISH_NAMES[d], (count.get(DISH_NAMES[d]) ?? 0) + 1);
  return count.size ? [...count].map(([n, k]) => `${n} ${k}`).join(', ') : 'нет';
}

/** Продукт по слову из пометки «[готовить: морковка, сыр]». */
function foodOf(word: string): string | null {
  const w = word.trim().toLowerCase().replaceAll('ё', 'е');
  if (w.startsWith('семеч')) return 'seeds';
  if (w.startsWith('яблок')) return 'apple';
  if (w.startsWith('морков')) return 'carrot';
  if (w.startsWith('сыр')) return 'cheese';
  if (w.startsWith('хлеб')) return 'bread';
  return null;
}

export type Emotion = 'joy' | 'laugh' | 'surprise' | 'sad' | 'think' | 'love' | 'sleepy';
export type Action = 'slide' | 'trampoline' | 'climber' | 'rope' | 'bath' | 'toilet' | 'table' | 'kitchen' | 'guitar';

const EMOTIONS: Record<string, Emotion> = {
  радость: 'joy', смех: 'laugh', удивление: 'surprise', грусть: 'sad', задумчивость: 'think', нежность: 'love', сонный: 'sleepy',
};
const ACTIONS: Record<string, Action> = {
  горка: 'slide', батут: 'trampoline', лазилка: 'climber', скакалка: 'rope', купаться: 'bath', туалет: 'toilet',
  кушать: 'table', готовить: 'kitchen', гитара: 'guitar',
};

/**
 * Пометки эмоции и действия из ответа модели («[эмоция: радость] [действие: горка] Ура!»).
 * Возвращает текст без пометок, что распознано, и сами пометки в едином виде (для истории).
 */
export interface Cues {
  text: string;
  emotion: Emotion | null;
  action: Action | null;
  /** Продукты для настоящей готовки (action = 'kitchen'). */
  cook: string[] | null;
  /** Пометки в едином виде — для истории. */
  tags: string;
  /** Пометки, которые не удалось понять (для журнала: чтобы поправить промпт). */
  unknown: string[];
}

export function extractCues(text: string): Cues {
  let emotion: Emotion | null = null;
  let action: Action | null = null;
  let cook: string[] | null = null;
  const unknown: string[] = [];
  const rest = text.replace(/\[\s*(эмоция|действие|готовить)\s*:\s*([^\]]{1,60})\]/gi, (all, kind: string, value: string) => {
    const k = kind.toLowerCase();
    const v = value.trim().toLowerCase().replaceAll('ё', 'е');
    if (k === 'эмоция') {
      if (EMOTIONS[v]) emotion ??= EMOTIONS[v];
      else unknown.push(all);
    } else if (k === 'действие') {
      if (ACTIONS[v]) action ??= ACTIONS[v];
      else unknown.push(all);
    } else {
      const foods = v.split(/\s*(?:,|\+|\sи\s)\s*/).map(foodOf);
      if (foods.length >= 2 && foods.length <= 3 && foods.every(Boolean)) {
        action ??= 'kitchen';
        cook ??= foods as string[];
      } else unknown.push(all);
    }
    return '';
  });
  const word = <T extends string>(map: Record<string, T>, id: T | null) => (id ? Object.keys(map).find((k) => map[k] === id) : '');
  const tags = [
    emotion && `[эмоция: ${word(EMOTIONS, emotion)}]`,
    cook ? `[готовить: ${(cook as string[]).map((f) => FOOD_NAMES[f]).join(', ')}]` : action && `[действие: ${word(ACTIONS, action)}]`,
  ]
    .filter(Boolean)
    .join(' ');
  return { text: rest, emotion, action, cook, tags, unknown };
}

/** Убрать из ответа модели то, что нельзя озвучивать: разметку, эмодзи, ремарки, пометки в скобках. */
export function cleanForSpeech(text: string): string {
  return text
    .replace(/<think>[\s\S]*?<\/think>/g, '')
    .replace(/\[[^\]]{0,60}\]/g, '')
    .replace(/\*[^*]{0,60}\*/g, '') // *смеется*
    .replace(/[*_#`>~|]/g, '')
    .replace(/\p{Extended_Pictographic}/gu, '')
    .replace(/\s+/g, ' ')
    .trim();
}
